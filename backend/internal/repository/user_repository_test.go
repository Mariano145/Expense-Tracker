package repository

import (
	"context"
	"errors"
	"os"
	"testing"
	"time"

	"github.com/gentle-ai/billetera/backend/internal/model"
	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// testPool creates a connection pool to the test database.
// The test database must exist and have migrations applied.
// Set TEST_DATABASE_URL env var or it defaults to a local test DB.
func testPool(t *testing.T) *pgxpool.Pool {
	t.Helper()

	dbURL := os.Getenv("TEST_DATABASE_URL")
	if dbURL == "" {
		dbURL = "postgres://billetera:billetera@localhost:5432/billetera_test?sslmode=disable"
	}

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	pool, err := pgxpool.New(ctx, dbURL)
	require.NoError(t, err, "failed to connect to test database")

	// Verify connection is alive.
	err = pool.Ping(ctx)
	require.NoError(t, err, "test database is not reachable")

	// Clean up tables before each test to ensure isolation.
	_, err = pool.Exec(ctx, "DELETE FROM refresh_tokens")
	require.NoError(t, err)
	_, err = pool.Exec(ctx, "DELETE FROM users")
	require.NoError(t, err)

	t.Cleanup(func() { pool.Close() })
	return pool
}

func TestUserRepository_Create(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping database test in short mode")
	}

	pool := testPool(t)
	repo := NewUserRepository(pool)

	t.Run("success - creates user and populates DB-generated fields", func(t *testing.T) {
		user := &model.User{
			Email:        "test@example.com",
			PasswordHash: "hashed_password_123",
		}

		err := repo.Create(context.Background(), user)
		require.NoError(t, err)

		// Verify DB-generated fields were populated.
		assert.NotEmpty(t, user.ID, "ID should be generated by database")
		assert.NotZero(t, user.CreatedAt, "CreatedAt should be set by database")
		assert.NotZero(t, user.UpdatedAt, "UpdatedAt should be set by database")
		assert.Equal(t, "test@example.com", user.Email)
	})

	t.Run("duplicate email - returns ErrEmailExists", func(t *testing.T) {
		user1 := &model.User{
			Email:        "duplicate@example.com",
			PasswordHash: "hash1",
		}
		err := repo.Create(context.Background(), user1)
		require.NoError(t, err)

		user2 := &model.User{
			Email:        "duplicate@example.com",
			PasswordHash: "hash2",
		}
		err = repo.Create(context.Background(), user2)
		require.Error(t, err)
		assert.True(t, errors.Is(err, model.ErrEmailExists), "expected ErrEmailExists, got: %v", err)
	})
}

func TestUserRepository_FindByEmail(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping database test in short mode")
	}

	pool := testPool(t)
	repo := NewUserRepository(pool)

	t.Run("found - returns user", func(t *testing.T) {
		user := &model.User{
			Email:        "findme@example.com",
			PasswordHash: "hash",
		}
		err := repo.Create(context.Background(), user)
		require.NoError(t, err)

		found, err := repo.FindByEmail(context.Background(), "findme@example.com")
		require.NoError(t, err)
		assert.Equal(t, user.ID, found.ID)
		assert.Equal(t, user.Email, found.Email)
		assert.Equal(t, user.PasswordHash, found.PasswordHash)
	})

	t.Run("not found - returns ErrUserNotFound", func(t *testing.T) {
		_, err := repo.FindByEmail(context.Background(), "nonexistent@example.com")
		require.Error(t, err)
		assert.True(t, errors.Is(err, model.ErrUserNotFound), "expected ErrUserNotFound, got: %v", err)
	})
}

