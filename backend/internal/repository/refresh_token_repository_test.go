func TestRefreshTokenRepository_RevokeByFamilyID(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping database test in short mode")
	}

	pool := testPool(t)
	userRepo := NewUserRepository(pool)
	repo := NewRefreshTokenRepository(pool)
	user := createTestUser(t, userRepo, "revokefamily-user@example.com")

	t.Run("success - revokes all tokens in the family", func(t *testing.T) {
		familyID := uuid.New().String()

		// Create 3 tokens in the same family.
		for i, hash := range []string{"fam-hash-1", "fam-hash-2", "fam-hash-3"} {
			token := &model.RefreshToken{
				UserID:    user.ID,
				TokenHash: hash,
				FamilyID:  familyID,
				ExpiresAt: time.Now().Add(7 * 24 * time.Hour),
			}
			err := repo.Create(context.Background(), token)
			require.NoError(t, err, "failed to create token %d", i)
		}

		// Create 1 token in a different family (should NOT be revoked).
		otherToken := &model.RefreshToken{
			UserID:    user.ID,
			TokenHash: "other-family-hash",
			FamilyID:  uuid.New().String(),
			ExpiresAt: time.Now().Add(7 * 24 * time.Hour),
		}
		err := repo.Create(context.Background(), otherToken)
		require.NoError(t, err)

		// Revoke the entire family.
		err = repo.RevokeByFamilyID(context.Background(), familyID)
		require.NoError(t, err)

		// Verify all 3 family tokens are revoked.
		for _, hash := range []string{"fam-hash-1", "fam-hash-2", "fam-hash-3"} {
			found, err := repo.FindByHash(context.Background(), hash)
			require.NoError(t, err)
			assert.True(t, found.Revoked, "token %s should be revoked", hash)
		}

		// Verify the other family's token is NOT revoked.
		found, err := repo.FindByHash(context.Background(), "other-family-hash")
		require.NoError(t, err)
		assert.False(t, found.Revoked, "token from different family should NOT be revoked")
	})
}

func TestRefreshTokenRepository_DeleteExpired(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping database test in short mode")
	}

	pool := testPool(t)
	userRepo := NewUserRepository(pool)
	repo := NewRefreshTokenRepository(pool)
	user := createTestUser(t, userRepo, "expired-user@example.com")

	t.Run("success - deletes only expired tokens", func(t *testing.T) {
		// Create an already-expired token.
		expired := &model.RefreshToken{
			UserID:    user.ID,
			TokenHash: "expired-hash",
			FamilyID:  uuid.New().String(),
			ExpiresAt: time.Now().Add(-1 * time.Hour), // expired 1 hour ago
		}
		err := repo.Create(context.Background(), expired)
		require.NoError(t, err)

		// Create a valid (non-expired) token.
		valid := &model.RefreshToken{
			UserID:    user.ID,
			TokenHash: "valid-hash",
			FamilyID:  uuid.New().String(),
			ExpiresAt: time.Now().Add(7 * 24 * time.Hour), // expires in 7 days
		}
		err = repo.Create(context.Background(), valid)
		require.NoError(t, err)

		// Delete expired tokens.
		deleted, err := repo.DeleteExpired(context.Background())
		require.NoError(t, err)
		assert.GreaterOrEqual(t, deleted, int64(1), "should have deleted at least 1 expired token")

		// Verify the expired token is gone.
		_, err = repo.FindByHash(context.Background(), "expired-hash")
		assert.True(t, errors.Is(err, model.ErrTokenNotFound), "expired token should be deleted")

		// Verify the valid token still exists.
		found, err := repo.FindByHash(context.Background(), "valid-hash")
		require.NoError(t, err)
		assert.Equal(t, valid.ID, found.ID)
	})
}
